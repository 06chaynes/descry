"""Standard-library types of the indexed languages.

`stdlib/<lang>.json` is generated by `tools/stdlib/`, never edited by hand:

    source     what it was generated from, with its version
    types      qualified type name -> {
                   "params":  generic parameter names, in order
                   "bases":   the types whose methods it also has, each with its
                              type arguments in terms of `params`
                   "methods": instance method name -> return type
                   "statics": static method name -> return type
               }
    functions  qualified function name -> return type
    scope      name visible without an import -> qualified type name
    variants   qualified type name -> {variant name -> the types of the values
               it holds: a list in their order, or by field name}
    callbacks  qualified type name -> {method name -> {argument position ->
               {"params": the parameter types of the callable passed there,
                "returns": the type parameter that stands for its result,
                           None where none does}}}

`variants` and `callbacks` are there only for a language that has them.

A return type is written as the language writes it, in terms of the type's
`params`; None when the method returns nothing or its overloads disagree.
"""

import json
from functools import cache
from importlib import resources


@cache
def load(lang: str) -> dict:
    """The generated data for `lang`, empty for a language that has none."""
    path = resources.files("descry") / "stdlib" / f"{lang}.json"
    if not path.is_file():
        return {"source": "", "types": {}, "functions": {}, "scope": {}}
    return json.loads(path.read_text(encoding="utf-8"))


@cache
def members(lang: str) -> frozenset:
    """The name of every method and static of the types `lang`'s data has."""
    types = load(lang)["types"].values()
    return frozenset().union(
        *(kind[t] for kind in types for t in ("methods", "statics"))
    )
