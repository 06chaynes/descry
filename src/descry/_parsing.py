def _constructs(value):
    """Whether ``value`` is one construction of an object, `new T(...)`."""
    found = re.match(r"new\s+[\\\w.$]+\s*\(", value)
    closed = found and _closing([value], 0, found.end())
    return bool(closed) and closed[1] == len(value) - 1


def _strip_parens(text: str) -> str:
    """``text`` without its parentheses and what they hold."""
    previous = None
    while text != previous:
        previous, text = text, re.sub(r"\([^()]*\)", "", text)
    return text


def _casts(expression: str) -> bool:
    """Whether ``expression`` opens with a type in parentheses that what
    follows is cast to: `(T) value`, where `(value).member` reads a member."""
    grouped = expression.lstrip()
    if not grouped.startswith("("):
        return False
    depth = 0
    for at, char in enumerate(grouped):
        depth += (char == "(") - (char == ")")
        if not depth:
            break
    return grouped[at + 1 :].lstrip()[:1] not in ("", ".", "?", ";", ")")


def _is_call_chain(expression: str) -> bool:
    """Whether ``expression``, once the arguments of its calls are taken
    out, is one chain of names: `a.b(x).c()`, `new T(x)`, `await f()`, or
    the `).c()` such a chain goes on with on a later line, an index or type
    arguments after a name, `a[i].b()` or `F[T](x)`, among them. A cast is
    none: its value has the type it is cast to."""
    chain = _strip_parens(_without_turbofish(expression))
    while (bare := re.sub(r"(?<=[\w)\]])\[[^\[\]]*\]", "", chain)) != chain:
        chain = bare
    return (
        not _casts(expression)
        and not _conditional(chain, 0, len(chain))
        and bool(
            re.fullmatch(
                r"[\s)]*(?:(?:await|new)\s+|&(?:mut\s+)?)*[\w$.:?\s]*;?\s*", chain
            )
        )
    )


def _conditional(code, start, end):
    """The column spans of the two branches of the conditional `c ? a : b`
    that the expression at columns ``start`` to ``end`` of ``code`` is,
    outside its brackets; None where it is none."""
    depth, open_, question = 0, 0, None
    for at in range(start, end):
        char, around = code[at], code[at - 1 : at + 2]
        depth += (char in "([{") - (char in ")]}")
        if depth or char not in "?:" or "??" in around or "::" in around:
            continue
        if char == "?" and code[at + 1 : at + 2] != ".":
            question = at if question is None else question
            open_ += 1
        elif char == ":" and open_:
            open_ -= 1
            if not open_:
                return (question + 1, at), (at + 1, end)
    return None


def _without_turbofish(text: str) -> str:
    """``text`` without Rust's `::<...>` type arguments."""
    while (at := text.find("::<")) >= 0:
        depth, end = 0, at + 2
        for end in range(at + 2, len(text)):
            depth += (text[end] == "<") - (text[end] == ">")
            if not depth:
                break
        text = text[:at] + text[end + 1 :]
    return text


def _code_units(text: str, before=(0, 0, 0)):
    """The UTF-8, UTF-16 and UTF-32 code units of ``text``, added to
    ``before``."""
    if text.isascii():
        return tuple(count + len(text) for count in before)
    return (
        before[0] + len(text.encode()),
        before[1] + len(text.encode("utf-16-le")) // 2,
        before[2] + len(text),
    )


def _scip_columns(units):
    """Column a SCIP index gives the character after text of ``units``
    code units on its line: one number, or ``(UTF-8, UTF-16, UTF-32)``
    code-unit offsets where those differ, in the order of SCIP's position
    encodings."""
    return units[2] if units[0] == units[2] else units


