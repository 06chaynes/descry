    def read_branches(self, reader=None, code_lines=()):
        """Take the statements ``reader`` reads from ``code_lines``, each
        ``(first, end, ways, on, exclusive)`` of one that runs a body only
        where its head allows: the ``(line, column)`` its first way starts
        and it ends at, the spans each way runs, those of the ways that go
        on past it, and whether its ways exclude each other, as an `if`'s
        do. None where the reader fails on a shape it does not know."""
        try:
            branches = reader(code_lines) if reader else []
        except Exception as e:  # noqa: BLE001 — a shape not read merges nothing
            file_id = self.builder.nodes[self._first_node]["id"]
            logger.warning(f"Branches of {file_id} not read: {e!r}")
            branches = []
        inner_first = sorted(branches, key=itemgetter(0), reverse=True)
        self._branchings = sorted(inner_first, key=itemgetter(1))
        self._next_branch = 0
        self._exclusive = sorted((b[:3] for b in branches if b[4]), key=itemgetter(1))
        self._exclusive_ends = [b[1] for b in self._exclusive]
        # ``(line, column)`` of each binding to ``null_literal`` and to an
        # object constructed
        self._nulls, self._made = set(), set()
        # Name -> the ends of the statements whose ways may leave it null
        self._maybe_null = {}
        # Line -> the names ``declared`` binds on it, and its keys sorted
        self._bound_lines = {}
        for name, entries in self.declared.items():
            for d in entries:
                self._bound_lines.setdefault(d[0], set()).add(name)
        self._bound_order = sorted(self._bound_lines)

    @staticmethod
    def _bound_names(lines, order, lo, hi):
        """The names of ``lines``, the map a binding's line to its names,
        bound on a line from ``lo`` to ``hi``, and the map's sorted keys."""
        return {
            name
            for line in order[bisect_left(order, lo) : bisect_right(order, hi)]
            for name in lines[line]
        }

    def _merge_branches(self, at, since):
        """Past each statement of ``read_branches`` that ends before
        position ``at``, give each name its ways through bind differently,
        read from line ``since`` on, no known value."""
        while self._next_branch < len(self._branchings):
            first, end, _, on, _ = self._branchings[self._next_branch]
            if end >= at:
                return
            self._next_branch += 1
            # Only a name bound inside can disagree; a way with none of it
            # holds the last bound before it, as every way's. Each statement
            # merges once for every scope: a binding of the file level takes
            # part wherever it is read from, one of another scope not, but in
            # a definition that sees none of the file's.
            for name in self._bound_names(
                self._bound_lines, self._bound_order, first[0], end[0]
            ):
                entries = self.declared.get(name)
                if not entries:
                    continue
                # What the statement's lines bind, and the last binding the
                # merge reads before them
                inside = [
                    ((d[0], self._column(name, d) or 0), d[1])
                    for d in entries.between(first[0], end[0])
                ]
                before = self._last_before(name, entries, first[0], since)
                bound = before + inside
                # A way that leaves the name null is no value a call is made
                # on, but one an assignment where it is null runs in.
                valued = self._last_before(name, entries, first[0], since, True) + [
                    b for b in inside if b[0] not in self._nulls
                ]
                if _disagree(valued, first, on):
                    entries.append((end[0], "?", False, end[1]))
                elif _disagree(bound, first, on) or _leaves_null(
                    bound, first, on, self._nulls
                ):
                    self._maybe_null.setdefault(name, []).append(end)

    def _last_before(self, name, entries, first, since, valued=False):
        """``[(position, value)]`` of the last of ``entries``, the bindings
        of ``name``, written before line ``first`` that a merge from line
        ``since`` reads, one from ``since`` on or at the file's level where
        the line sees the file's, not null where ``valued``; [] for none."""
        groups = entries.lines_down(first - 1, since)
        if first < since or self._sees_file():
            top = entries.lines_down(min(first, since) - 1, 0, top=True)
            groups = chain(groups, top)
        for group in groups:
            found = [
                b
                for d in group
                if d[0] >= since or d[2]
                for b in [((d[0], self._column(name, d) or 0), d[1])]
                if not (valued and b[0] in self._nulls)
            ]
            if found:
                return [max(reversed(found), key=itemgetter(0))]
        return []

    def enter_context(self, node_id, first_line, last_line, params=frozenset()):
        """Make ``node_id``, which spans ``first_line`` to ``last_line``, the
        innermost context. ``params`` are the names of its parameters."""
        self._contexts.append((node_id, first_line, last_line, params))

    def context_at(self, lineno):
        """``(node ID, first line)`` of the innermost context entered that
        reaches line ``lineno``. Lines are asked for in ascending order."""
        while lineno > self._contexts[-1][2]:
            self._contexts.pop()
        return self._contexts[-1][:2]

    def enclosing_scope(self, node_id):
        """The innermost context around ``node_id``: where a class or an
        object it defines is evaluated."""
        for context in reversed(self._contexts):
            if context[0] != node_id:
                return context[0]
        return node_id

    @staticmethod
    def leave_contexts(contexts, levels, level):
        """Pop the innermost context, never the first, for as long as its
        entry in ``levels``, the brace depth or indentation it was entered
        at, is ``level`` or more."""
        while len(contexts) > 1 and level <= levels[-1]:
            contexts.pop()
            levels.pop()

    def scan_declarations(self, lines, patterns, scope=None):
        """Record every declaration in ``lines`` that one of ``patterns``
        reads as ``name`` having type ``type``, or as type parameter
        ``param`` being bounded by ``type``. With ``scope`` a type whose
        arguments hold a tuple is read, as written there, from
        ``parameter_types``."""
        # name -> [(lineno, origin of its value, at file level, column)], and
        # <param> -> [(lineno, bound, at file level, column)]; the column of
        # the name on the line, None where the line does not tell
        self.declared = _BoundMap(self)
        self._members = set()  # (lineno, name) of members, read on a receiver
        self.fields, self._field_lines = {}, {}
        depth = 0  # parentheses open at the start of the line
        owner = None  # type whose body the line is in
        for lineno, line in enumerate(lines, 1):
            if line[:1].strip():
                depth = 0
                owner = None
            if header := _TYPE_HEADER_RE.search(line):
                owner = header[1] or header[2] or header[3]
            for pattern in patterns:
                for match in pattern.finditer(line):
                    groups = match.groupdict()
                    declared_type = self._scanned_type(groups)
                    # Unindented and not in a parameter list or a body.
                    named = match.start("name") if groups.get("name") else match.start()
                    file_level = not line[:1].isspace() and not re.search(
                        r"[({]", line[:named]
                    )
                    if groups.get("name"):
                        held = _raw_pointer(declared_type, groups.get("pointer"))
                        key, value = groups["name"], f"{held}()"
                        arguments = (
                            scope
                            and groups.get("generic")
                            and ", ".join(
                                _bracketed_parts(line[match.end("generic") :])
                            )
                        )
                        if arguments and _TUPLE_ARGUMENT_RE.search(arguments):
                            value = f"{{{self.builder.serial(self.builder.parameter_types)}}}"
                            written = f"{groups['type']}<{arguments}>"
                            self.builder.parameter_types[value] = written, scope
                        if self.language == "clang" and line[match.end() :].startswith(
                            "["
                        ):
                            # A C array: `T()[]`, of elements of the type.
                            value += "[]"
                        if self.language == "clang" and declared_type == "auto":
                            # `for (auto& name : expr)` — `name` holds what
                            # iterating `expr` gives: what a call it is
                            # returns, or `*expr`, what the variable or the
                            # field `expr` holds where the call is read.
                            iterated = re.match(
                                r"\s*([\w.:>-]+(?:\(\))?)", line[match.end() :]
                            )
                            if iterated:
                                name = iterated[1]
                                value = (
                                    f"={name}.?" if name.endswith("()") else f"*{name}"
                                )
                    else:
                        key, value = f"<{groups['param']}>", declared_type
                    # What is declared `typeof x` holds `x` itself.
                    queried = _TS_TYPEOF_RE.fullmatch(groups["type"])
                    held = value
                    if queried:
                        # `x`, or what the file declares `x` as where it does
                        top = self.declared.get(queried[1], ())
                        known = [v for _, v, at_top, _ in top if v and at_top]
                        held = known[-1] if known else queried[1]
                    before = line[: match.start("name")] if groups.get("name") else None
                    # `this.name`/`self.name` writes a member of the type the
                    # line is in, no variable of the name.
                    written = before is not None and re.search(
                        rf"(?<![\w$.]){re.escape(self.self_name)}\.$", before.rstrip()
                    )
                    self.declared.setdefault(
                        f"{owner or ''}.{key}" if written else key, []
                    ).append((lineno, held, file_level, named))
                    if self._property(lineno, line, named, match[0], key):
                        self._members.add((lineno, key))
                    # A field is declared at the start of a line, behind
                    # modifiers at most, and not among parameters.
                    if (
                        before is not None
                        and owner
                        and not depth
                        and _FIELD_MODIFIERS_RE.fullmatch(before)
                    ):
                        self.fields.setdefault((owner, key), set()).add(value)
                        self._field_lines.setdefault((owner, key), {})[lineno] = value
            depth = max(0, depth + line.count("(") - line.count(")"))

    def _scanned_type(self, groups):
        """The type that a declaration ``scan_declarations`` matches, with
        ``groups``, gives its name, as one step of an origin path."""
        declared_type = re.sub(r"\s*::\s*|\.", "::", groups["type"])
        # A Rust literal's `Type::<A> { .. }` is a `Type<A>`.
        declared_type += (groups.get("turbofish") or "").removeprefix("::")
        if groups.get("generic"):
            # C# keeps what the type's arguments are: an array's element
            # carries its `IEnumerable<T>`.
            keeps = self.language in ("dotnet", "dart")
            declared_type += groups["generic"] if keeps else "<>"
        # C# `T?`, which for a value type is another type
        return declared_type + (groups.get("nullable") or "")

    def _seen(self, name, lineno, since):
        """The entry of ``declared`` for ``name`` a read at ``lineno`` sees:
        its last declaration in scope from line ``since``, the start of the
        enclosing definition, written before the read; None for none."""
        if lineno == self._line and self._read_at is not None:
            # What a binding before the read on its line is bound to
            self._settle_calls(self._code, self._read_at)
        if lineno < self._line or self._read_at is not None:
            # A statement that ends before the read merges for it, on its
            # line too; a line with no read column binds before it merges.
            self._merge_branches(
                (lineno, self._read_at if self._read_at is not None else math.inf),
                since,
            )
        read = lineno, self._read_at
        entries = self.declared.get(name)
        # Of those in scope written before the read, the ones of the last
        # line that has one
        same = []
        for group in entries.lines_down(lineno, since) if entries else ():
            same = [
                d
                for d in group
                if (d[0], name) not in self._members
                and self._in_scope(name, d, lineno)
                and (read[1] is None or (d[0], self._column(name, d) or 0) < read)
                and not _apart(
                    self._exclusive,
                    (d[0], self._column(name, d) or 0),
                    (lineno, read[1] or 0),
                    ends=self._exclusive_ends,
                )
            ]
            if same:
                break
        if not same:
            return None
        line = same[0][0]
        columns = [self._column(name, d) for d in same]
        if None not in columns and (line < lineno or read[1] is not None):
            # The last of the line
            same = [max(zip(columns, same), key=lambda b: b[0])[1]]
        return same[0]

    def _runs(self, name, lineno, since, where_null):
        """Whether an assignment to ``name`` on line ``lineno`` that runs only
        where the name holds ``null_literal``, if ``where_null``, else only
        where it holds an object, runs: None where either may be. A binding
        to an object constructed holds one; a value of any other kind may be
        null."""
        # The statements that end before the line have merged.
        self._merge_branches((lineno, 0), since)
        seen = self._seen(name, lineno, since)
        if seen is None:
            return None
        at = seen[0], self._column(name, seen) or 0
        if any(end > at for end in self._maybe_null.get(name, ())):
            # A merge past the write left it maybe null, maybe an object.
            return None
        if at in self._nulls:
            null = True
        elif at in self._made:
            null = False
        else:
            return None
        return null == where_null

    def _declared(self, name, lineno, since, anywhere=False):
        """What ``name`` is declared as at ``lineno``: by the declaration
        ``_seen`` gives. Failing that what its file-level declarations agree
        on. ``anywhere`` looks at every declaration instead, for a field."""
        seen = None if anywhere else self._seen(name, lineno, since)
        if seen is not None:
            return seen[1]
        entries = self.declared.get(name) or _BoundEntries(None, name)
        # What a call returned is bound to a variable, never to a field. A
        # parameter or variable of the definition hides a file-level name.
        hidden = self._is_local(name) or not self._sees_file()
        # The values that can count: for a field any known one; the
        # file-level ones but where hidden; and those before the line where
        # read at the file's level
        if anywhere:
            values = set(entries.valued) | set(() if hidden else entries.top_values)
            if not since and len(values) < 2:
                values.update(d[1] for d in entries.between(0, lineno))
        else:
            values = {
                d[1]
                for d in chain(
                    () if hidden else chain(*entries.lines_down(math.inf, 0, top=True)),
                    () if since else entries.between(0, lineno),
                )
                if (d[0], name) not in self._members
                and (
                    d[2]
                    and not hidden
                    and self._item_reaches(name, d, lineno)
                    or not since
                    and d[0] <= lineno
                )
            }
        return values.pop() if len(values) == 1 else None

    def read_blocks(self, code_lines, brackets=None):
        """Scope each local declaration by the block it is in, for a language
        whose blocks scope what they declare. ``code_lines`` are the lines
        declarations are read from, without comments and literal text, and
        ``brackets`` what ``_js_brackets`` reads of them where known."""
        text, starts, closer = brackets or _js_brackets(code_lines)
        self._blocks = text, starts, closer, _nested(sorted(closer.items()))
        self._scope_extents = {}

    def _in_scope(self, name, declaration, lineno):
        """Whether ``declaration``, an entry of ``declared`` for ``name``, is
        in scope where line ``lineno`` is read, at column ``_read_at`` where
        known."""
        if declaration[2] and not self._sees_file():
            return False
        if self._blocks is None:
            return True
        key = name, declaration
        if key not in self._scope_extents:
            self._scope_extents[key] = self._scope_spans(*key)
        read = self._blocks[1][lineno - 1] + (self._read_at or 0)
        return any(start <= read <= end for start, end in self._scope_extents[key])

    def _scope_spans(self, name, declaration):
        """The spans of the code, ``(start, end)`` offsets, where
        ``declaration``, an entry of ``declared`` for ``name``, is in scope."""
        return [(0, self._scope_end(name, declaration))]

    def _column(self, name, declaration):
        """The column of ``declaration``, an entry of ``declared`` for
        ``name``, on its line. One of no column has, in a file read by
        blocks, where the line first names it, else its end: that of a
        statement whose value binds it once read; None in any other."""
        line, column = declaration[0], declaration[3]
        if column is not None or self._blocks is None:
            return column
        text, starts = self._blocks[:2]
        found = _named(text, name, starts[line - 1], starts[line] - 1)
        return (starts[line] - 1 if found is None else found) - starts[line - 1]

    def _declaration_site(self, name, declaration):
        """``(at, head, block, written)`` of ``declaration``, an entry of
        ``declared`` for ``name``: the offset it is at, the outermost bracket
        around it that opens no block if any, the block around both if any,
        and the statement up to that bracket, or up to the declaration."""
        text, starts, closer, spans = self._blocks
        at = starts[declaration[0] - 1] + self._column(name, declaration)

        def statement(offset):
            """The statement on the line up to ``offset``, past each control
            head it follows without braces."""
            start = text.rfind("\n", 0, offset) + 1
            start = max(start, *(text.rfind(c, start, offset) + 1 for c in ";{}"))
            while found := _BRACELESS_HEAD_RE.match(text, start, offset):
                end = (
                    closer.get(found.start(1), offset) + 1 if found[1] else found.end()
                )
                if end > offset:
                    break
                start = end
            return text[start:offset]

        held, head = _innermost(spans, at), None
        # Out of parentheses, brackets and braces that open no block: a
        # group of parameters, or a pattern a declaration takes apart
        while held and (
            text[held[0]] in "(["
            or statement(held[0]).rstrip()[-1:] in ("(", ",")
            or self._pattern_head(statement(held[0]))
        ):
            head, held = held, _innermost(spans, held[0])
        return at, head, held, statement(head[0] if head else at)

    def _pattern_head(self, statement):
        """Whether ``statement``, the code of a statement up to a brace,
        heads a pattern there: the brace opens no block."""
        return _DECLARING_STATEMENT_RE.match(statement)

    def _scope_end(self, name, declaration):
        """The offset in the code where the scope of ``declaration``, an
        entry of ``declared`` for ``name``, ends: the end of the block it is
        in or, for a name a statement's head or parameters declare, of that
        statement, and for one a `case` label declares, where
        ``case_scopes_section`` says, of its switch section."""
        text = self._blocks[0]
        at, head, held, written = self._declaration_site(name, declaration)
        if name[0] == "<":
            # A type parameter is the definition's whose head declares it.
            return self._statement_close(at)
        if self.case_scopes_section and held and re.match(r"\s*case\b", written):
            return self._section_end(at, held)
        if head and not _DECLARING_STATEMENT_RE.match(written):
            return self._statement_close(head[1] + 1, self.head_scopes_else)
        if not head and _HEADING_STATEMENT_RE.match(written):
            return self._statement_close(at, self.head_scopes_else, heading=True)
        return held[1] if held else len(text)

    def _section_end(self, at, block):
        """The offset where the switch section going on at offset ``at`` of
        the switch's ``block`` ends: at the next label, else at its end."""
        spans = self._blocks[3]
        labels = _CASE_LABEL_RE.finditer(self._blocks[0], at, block[1])
        ends = (m.start() for m in labels if _innermost(spans, m.start()) == block)
        return next(ends, block[1])

    def _statement_close(self, at, orelse=True, heading=False):
        """The offset where the statement going on at offset ``at`` ends: at
        the `}` of the block it goes on to, past an initializer list's `,`, a
        block that follows and, with ``orelse``, an `else` after the block
        or the `;`, at its `;`, or at the bracket that closes what it is in.
        ``heading`` reads a keyword's head, which a `;` does not end, and
        where a `{` after an array, a slice or a map type opens a literal.
        An `if` the statement is takes the `else` after it, as the nearest
        `if` does."""
        text, _, closer, _ = self._blocks
        inner = not heading and _IF_RE.match(text, at)
        if inner and inner.end() - 1 in closer:
            then, other = self._if_branches(closer[inner.end() - 1])
            at = (other or then)[1]
            more = orelse and _ELSE_RE.match(text, at + 1)
            return self._statement_close(more.end(), False) if more else at
        goes_on = re.compile(
            r"\s*(?:else\b|,|(?=\{))" if orelse else r"\s*(?:,|(?=\{))"
        )
        while at < len(text):
            char = text[at]
            if char == "{" and not (
                heading and _LITERAL_TYPE_RE.search(text, max(at - 80, 0), at)
            ):
                at = closer.get(at, len(text))
                more = goes_on.match(text, at + 1)
                if not more:
                    return at
                at, heading = more.end(), False
            elif char in "([{":
                at = closer.get(at, len(text)) + 1
            elif char == ";" and orelse and (more := _ELSE_RE.match(text, at + 1)):
                at = more.end()
            elif char in ")]}" or (char == ";" and not heading):
                return at
            else:
                at += 1
        return len(text)

    def _exits(self, start):
        """Whether the statement at offset ``start``, a branch, ends by
        leaving the statement around it."""
        text, _, closer, _ = self._blocks
        at = re.compile(r"\s*(?:else\b\s*)?").match(text, start).end()
        if text.startswith("{", at):
            body = text[at + 1 : closer.get(at, at)]
        else:
            body = text[at : text.find(";", at) + 1]
        return bool(_EXITS_RE.search(body))

    def _if_branches(self, closed):
        """``(then, orelse)``: the spans of the branches of the `if` whose
        condition closes at offset ``closed``, ``orelse`` None for none."""
        then = (closed + 1, self._statement_close(closed + 1, orelse=False))
        more = _ELSE_RE.match(self._blocks[0], then[1] + 1)
        return then, more and (then[1] + 1, self._statement_close(more.end(), False))

    def _branch_scope(self, closed, held, holds):
        """The spans where what the condition of an `if` tells when it is
        ``holds`` is known, the condition closing at offset ``closed`` in
        the block ``held``: the branch it is ``holds`` in, and past the `if`
        to the end of the block where the other branch exits."""
        then, orelse = self._if_branches(closed)
        branch, other = (then, orelse) if holds else (orelse, then)
        spans = [branch] if branch else []
        if other and self._exits(other[0]):
            end = held[1] if held else len(self._blocks[0])
            spans.append(((orelse or then)[1] + 1, end))
        return spans

    def _property(self, lineno, line, column, declared, name):
        """Whether ``declared``, a declaration of ``name`` the scan read at
        column ``column`` of ``line``, line ``lineno``, is a property, no
        name in scope."""
        return False

    def call_origin(self, callee, lineno, since, owner=None):
        """Origin path (see ``PythonParser._origin``) of a `receiver.method`
        callee whose receiver has a declared type or was bound to a call's
        result; None for any other. ``since`` is the first line of the
        enclosing definition, or 0 when the parser does not track one, and
        ``owner`` the name of the type `self` or `this` is an instance of."""
        receiver, _, method = callee.rpartition(".")
        field = receiver.removeprefix("this.").removeprefix("self.")
        member = field != receiver
        # A member read on the receiver, `b.held.meow`, follows it.
        field, _, path = field.partition(".")
        if member:
            # `this.field`/`self.field` holds what the type `this` is an
            # instance of — or one it inherits — declares or assigns it. A
            # subtype's writes are no instance of its base's.
            # What the type declares it, else what its code writes to it,
            # else what a field of the name the scan could not file under its
            # type holds
            owners = [owner or "", *self._inherited_names(owner)]
            types = {t for o in owners for t in self.fields.get((o, field), ())}
            for read in (f"{o}.{field}" for o in owners) if not types else ():
                types.add(self._declared(read, lineno, since, True))
            types.discard(None)
            if not types and (held := self._declared(field, lineno, since, True)):
                types.add(held)
            value = types.pop() if len(types) == 1 else None
        else:
            value = self._declared(field, lineno, since)
        seen = {field}
        while value and value not in seen and value in self.declared:
            # `typeof name` holds what the name is declared as there.
            seen.add(value)
            value = self._declared(value, lineno, since) or value
        if value is None:
            return None
        if not value.startswith("#"):
            # A type parameter stands for its bound.
            bounds = self._bounds(value[:-2], lineno)
            value = f"{bounds.pop()}()" if len(bounds) == 1 else value
        return f"{value}.{path}.{method}" if path else f"{value}.{method}"

    def _owning_type(self, scope_id):
        """The name of the type a `self` or `this` written in ``scope_id``
        is an instance of: the innermost class enclosing it, else None."""
        while "::" in scope_id:
            node = self._node(scope_id)
            if node and node["type"] == "Class":
                return node["metadata"]["name"]
            scope_id = scope_id.rpartition("::")[0]
        return None

    def _inherited_names(self, owner):
        """The names of the types ``owner`` inherits, direct or not, as the
        file being parsed names them."""
        if owner is None:
            return ()
        first, read, named = self._bases_named
        if first != self._first_edge:
            read, named = self._first_edge, {}
        for edge in self.builder.edges[read:]:
            if edge["relation"] == "INHERITS" and edge["target"].startswith("REF:"):
                base = edge["target"][4:]
                named.setdefault(edge["source"].rpartition("::")[2], set()).add(
                    base.rpartition(".")[2] or base
                )
        self._bases_named = self._first_edge, len(self.builder.edges), named
        seen = {owner}
        queue = [owner]
        for t in queue:
            for base in named.get(t, ()):
                if base not in seen:
                    seen.add(base)
                    queue.append(base)
        return seen - {owner}

    def _bounds(self, param, lineno):
        """The bounds of type parameter ``param`` where line ``lineno`` is
        read: those the innermost declaration of it in scope there gives
        it."""
        key = f"<{param}>"
        entries = self.declared.get(key)
        # The scan writes a type parameter's declarations in line order.
        for group in entries.lines_down(lineno, 0) if entries else ():
            if held := {d[1] for d in group if self._in_scope(key, d, lineno)}:
                return held
        return set()

    def begin_line(self, code, lineno, scope=None, raw=None, since=0, owner=None):
        """Start reading the calls of ``code``, source line ``lineno``. Call
        this for every line whose calls are recorded, in order. ``scope`` is
        the definition a variable the line binds is local to, ``raw`` the
        line as written where ``code`` has its literals blanked, and
        ``since`` and ``owner`` what ``call_origin`` takes for the line."""
        finished = self._code
        self._end_line()
        self._settle_calls(finished, math.inf)
        self._merge_branches((lineno, 0), since)
        # (name, end, value's start and end columns, steps from the call's
        # result to the name's) of each binding of the line whose statement
        # ends on it and whose value is not known
        self._unsettled = []
        for pending in [p for p in self._spanning if p[1][0] < lineno]:
            self._spanning.remove(pending)
            name, end, start, stop, unwrap = pending
            held = self._span_origin(start, stop)
            if held and (end[0], "?", False, end[1]) in self.declared.between(
                name, end[0], end[0]
            ):
                self._settle(name, *end, held + unwrap)
        self._line, self._code = lineno, code
        self._scope, self._raw = scope, raw or code
        self._since = since
        self._units = 0, (0, 0, 0)
        self._pairs, self._closes = {}, {}
        # Each binding the line declares holds from where its statement ends
        # what it copies where its value is a name or a field, else no known
        # value until the value is read, unless the parser read the
        # declaration already.
        ahead = self.binds_ahead and self.binding_re
        for found in ahead.finditer(code) if ahead else ():
            end = self._ended(code, lineno, found.end())
            stop = end[1] if end[0] == lineno else len(code)
            for name, at, start, value_end, result in self._bound_values(
                found, code, stop
            ):
                written = {(lineno, at), end}
                if not self.declares(found):
                    continue
                if found.groupdict().get("cond"):
                    # `name ??= value` assigns only where `name` is null or
                    # unset: one holding an object keeps it, one that may
                    # be either holds no known value.
                    runs = self._runs(name, lineno, since, True)
                    if runs is False:
                        continue
                    if runs is None:
                        self.declared.setdefault(name, []).append(
                            (end[0], "?", False, end[1])
                        )
                        continue
                value = code[start:value_end].strip()
                if value.lower() == self.null_literal:
                    self._nulls.update(written)
                elif _constructs(value):
                    self._made.update(written)
                if any(
                    (e[0], e[3]) in written
                    for e in self.declared.between(
                        name, min(written)[0], max(written)[0]
                    )
                ):
                    continue
                # Of a value that gives several, the first is the value
                copied = (
                    end[0] == lineno
                    and not result
                    and (
                        self._expression_origin(
                            code, start, value_end, lineno, since, owner
                        )
                        or self._item_origin(value, lineno, start, since)
                    )
                )
                held, unwrap = "?", ".?" * bool(found.groupdict().get("unwrap"))
                if copied:
                    held = copied + unwrap
                elif end[0] == lineno:
                    # A call's result, of one that gives several the name's
                    steps = ("" if result is None else f".@{result}") + unwrap
                    self._unsettled.append((name, end, start, value_end, steps))
                elif self._blocks is not None and not result:
                    # A value that goes on below, read once its statement ends
                    starts = self._blocks[1]
                    span = starts[lineno - 1] + start, starts[end[0] - 1] + end[1]
                    self._spanning.append((name, end, *span, unwrap))
                self.declared.setdefault(name, []).append((end[0], held, False, end[1]))
        self._parens, self._innermost = [], [None]
        if code[:1].strip() and code[0] not in ")}]":
            # An unindented line starts a top-level item, unless it opens
            # with what closes the one before.
            self._open_calls.clear()
            self._carried, self._carried_labels = "", []
        self._brackets, self._inside = [], [(None, self._carried[-1:])]
        self._inside_labels = [
            self._carried_labels[-1] if self._carried_labels else None
        ]
        stack, brackets = [], []
        depth = self._pending[2] if self._pending else None
        for column, char in enumerate(code):
            if char == "(":
                stack.append(column)
            elif char == ")" and stack:
                self._pairs[stack.pop()] = column
            elif char == ")" and self._open_calls:
                self._closes[column] = self._open_calls.pop()
                if len(self._open_calls) == depth:
                    self._pending_closed = column
            if char in "()":
                self._parens.append(column + (char == "("))
                self._innermost.append(stack[-1] if stack else None)
            if char in "([{":
                brackets.append(column)
            elif char not in ")]}":
                continue
            elif brackets:
                brackets.pop()
            else:
                self._carried, self._carried_labels = (
                    self._carried[:-1],
                    self._carried_labels[:-1],
                )
            self._brackets.append(column + (char in "([{"))
            self._inside.append(
                (brackets[-1], code[brackets[-1]])
                if brackets
                else (None, self._carried[-1:])
            )
            held = not brackets and self._carried_labels
            self._inside_labels.append(held[-1] if held else None)
        self._carried += "".join(code[column] for column in brackets)
        self._left_open = brackets
        self._opens = dict.fromkeys(stack)

    def _end_line(self):
        """Carry what the finished line leaves open over to the next: its
        unclosed calls, the call it ends with, and what it binds, returning
        the entry of ``declared`` it binds, else None. A line whose code is
        blank ends nothing — comments and preprocessor lines leave the open
        statement alone."""
        if not self._code.strip():
            return
        self._carried_labels += [
            self._held_label(self._code, c) for c in self._left_open
        ]
        open_before = len(self._open_calls)
        self._open_calls.extend(self._opens.values())
        statement = self._code.rstrip().rstrip(";").rstrip()
        # `?` unwraps; in TypeScript `!` asserts what it ends is not null.
        value = statement.rstrip("?!" if self.language == "typescript" else "?")
        # A `.` a line ends with is a member's, where it is no range's,
        # spread's or number's: the next line goes on with that member.
        dot = bool(re.search(r"(?<!\.)\.\Z", value)) and not _NUMBER_DOT_END_RE.search(
            value
        )
        chain = value[:-1].rstrip() if dot else value
        called = chain.rstrip("?")
        prior = self._tail, self._tail_unwraps, self._tail_fields
        # The fields read after the call the line ends with, or on the call
        # the line before ends with by a line of fields alone
        fields = self.call_fields and re.search(r"(?<=\))(?:\.[A-Za-z_]\w*)+$", called)
        end = fields.start() if fields else len(called)
        tail = self._closes.get(end - 1) if called else None
        # An index the line ends with, read while the line before's call is
        # still the one an index alone on the line is of
        indexed = tail is None and called.endswith("]") and self._scope
        held = indexed and self._element_origin(
            len(called), "x", self._line, self._since, self._scope
        )
        self._tail = tail
        self._tail_fields = fields[0] if fields else ""
        self._tail_unwraps = len(statement) - len(value) + len(chain) - len(called)
        if not called.strip() and statement.strip() and prior[0] is not None:
            # A line of `?` alone unwraps the call the line before ends with.
            self._tail, self._tail_fields = prior[0], prior[2]
            self._tail_unwraps += prior[1]
        if (
            self.call_fields
            and self._tail is None
            and prior[0] is not None
            and re.fullmatch(r"\s*(?:\.[A-Za-z_]\w*)+", called)
        ):
            self._tail = prior[0]
            self._tail_fields = prior[2] + ".?" * prior[1] + called.strip()
        ends_with = None if self._tail is not None else _TRAILING_PATH_RE.search(chain)
        self._tail_element = (held and held.removesuffix(".x")) or (
            self._tail is None and self._closed_value(called)
        )
        continued, self._tail_dot = self._tail_dot, dot
        if ends_with and continued and not chain[: ends_with.start()].strip():
            # The path goes on from the one the line before ends with.
            self._tail_name = self._tail_name and f"{self._tail_name}.{ends_with[0]}"
        elif not continued and (path := self._continued_path(chain)):
            # As it does from a line of fields alone, `.items`, below it.
            self._tail_name = path
        else:
            self._tail_name = ends_with and ends_with.group()
        binding = self.binding_re.search(self._code) if self.binding_re else None
        if binding and (
            not self._binds_name(binding["name"]) or binding.groupdict().get("cond")
        ):
            # A name the file gets from elsewhere is no declaration of it,
            # and `begin_line` binds what an assignment where null gives.
            binding = None
        closed, self._pending_closed = self._pending_closed, None
        below, self._value_below = self._value_below, False
        depth = None
        # The declaration that gives the name a type, where the binding has one
        declares = None
        if binding:
            name, unwrap = binding["name"], bool(binding.groupdict().get("unwrap"))
            expression = self._code[binding.end() :]
            if self._scope and self.declares(binding):
                self.add_local(self._scope, name)
            declares = self._typed_declaration(name, binding.start("name"))
            self._value_below = not expression.strip()
            # The value goes on over the next lines inside the call it
            # starts with.
            opened = [column for column in self._opens if column >= binding.end()]
            if opened and _is_call_chain(self._code[binding.end() : opened[0]]):
                depth = open_before + list(self._opens).index(opened[0])
        elif self._pending and closed is not None:
            name, unwrap, _ = self._pending
            declares = self._pending_typed
            expression = self._code[closed:]
        elif (
            self._pending
            and self._pending[2] is not None
            and len(self._open_calls) > self._pending[2]
        ):
            self._code = ""
            return
        elif self._pending and (
            continued or below or self._code.lstrip()[:1] in (".", ")")
        ):
            name, unwrap, _ = self._pending
            declares = self._pending_typed
            expression = self._code
            opened = list(self._opens)
            if (
                self.chained_values
                and opened
                and _is_call_chain(expression[: opened[0]])
            ):
                depth = open_before
        else:
            name = None
        self._pending = (name, unwrap, depth) if name else None
        self._pending_typed = declares if name else None
        if binding and not self.binds_ahead:
            self._bound_at = self._line, binding.start("name")
        # Where the binding's statement ends, where its unknown value is, or
        # where it binds across lines the line's end; the binding itself
        # where the file's scopes tell where it holds
        if not self.binds_ahead:
            where = self._bound_at
        elif binding:
            where = self._ended(self._code, self._line, binding.end())
        else:
            where = self._line, len(self._code)
        self._code = ""
        if name is None or self._tail is None:
            return
        if not (value.endswith(")") or self._tail_fields):
            return
        # Bind only where the whole value is one call chain.
        if _is_call_chain(expression):
            unwraps = max(unwrap, len(statement) - len(value))
            origin = f"#{self._tail}{self._tail_fields}" + ".?" * unwraps
            entries = self.declared.setdefault(name, [])
            # A type the file declares the name with is what it is read as.
            typed = entries.typed_top
            # Where the binding declares the name's type, the call's result
            # is read through that type: one declaration, holding both, or
            # the type alone from where the statement ends.
            if declares and declares in entries.between(declares[0], declares[0]):
                read_as = self._typed_origin(origin, declares[1])
                if not read_as:
                    return self._settle(name, *where, declares[1], declares[2])
                line, _, top, at = declares
                bound = line, read_as, top or self._binds_file(name), at
                entries[entries.index(declares)] = bound
                return bound
            top = self._binds_file(name) and not typed
            return self._settle(name, *where, origin, top)

    def _ended(self, code, lineno, at):
        """``(line, column)`` where the statement going on at column ``at``
        of ``code``, line ``lineno``, ends: at its `;` or the end of a line
        ``line_ends_statement`` matches, else at the bracket that closes what
        holds it."""
        if self._blocks is None:
            return lineno, _ends_at(code, at)
        text, starts, closer, _ = self._blocks
        end = starts[lineno - 1] + at
        ends = self.line_ends_statement
        while end < len(text) and text[end] not in ";)]}":
            if (
                text[end] == "\n"
                and ends
                and ends.search(text, starts[bisect_right(starts, end) - 1], end)
            ):
                break
            end = closer.get(end, end) + 1
        return self._place(end)

    def _place(self, at):
        """``(line, column)`` of offset ``at`` of the code ``read_blocks``
        read."""
        starts = self._blocks[1]
        line = bisect_right(starts, at)
        return line, at - starts[line - 1]

    def _settle_calls(self, code, before):
        """Give each binding of ``code``, the line being read, whose
        statement ends before column ``before``, whose value is a call chain
        the line has read, or a name the line has bound since, and which
        holds no known value yet, what the call returns or the name holds,
        in the order the statements end. A binding is off the list while
        its value is read, which may read the line's names again."""
        for unsettled in sorted(self._unsettled, key=itemgetter(1)):
            name, end, start, stop, steps = unsettled
            if end[1] >= before:
                return
            if unsettled not in self._unsettled:
                continue
            self._unsettled.remove(unsettled)
            value = code[start:stop].rstrip()
            edge = self._closes.get(start + len(value) - 1)
            held = None
            if edge is not None and _is_call_chain(value.strip()):
                held = f"#{edge}{steps}"
            elif held := self._settled_origin(code, start, stop, end[0]):
                held += steps
            if not held:
                self._unsettled.append(unsettled)
            elif (end[0], "?", False, end[1]) in self.declared.between(
                name, end[0], end[0]
            ):
                self._settle(name, *end, held)

    def _settled_origin(self, code, start, stop, lineno):
        """Origin path of a binding's value at columns ``start`` to ``stop``
        of ``code``, line ``lineno``, once the line has read the calls in it:
        a construction, or a name the line has bound since; None for any
        other."""
        value = code[start:stop].strip()
        if built := self._constructed(value):
            return built
        if re.fullmatch(r"[A-Za-z_]\w*", value):
            return self._expression_origin(code, start, stop, lineno, self._since, None)
        return None

    def _span_origin(self, start, stop):
        """Origin path of the value at offsets ``start`` to ``stop`` of the
        code ``read_blocks`` read, over lines; None where the language reads
        none."""

    def _bound_values(self, found, code, end):
        """``(name, column, start, end, result)`` of each name that
        ``found``, a match of ``binding_re`` on ``code`` whose statement ends
        at column ``end``, binds: its column, those of the value it takes,
        and where the value gives several, the position of the name's, else
        None."""
        return [(found["name"], found.start("name"), found.end(), end, None)]

    def _settle(self, name, line, column, held, top=False):
        """Give the binding of ``name`` whose statement ends at ``column`` of
        line ``line`` the value ``held``, in place of the unknown one it has
        from there, and return its entry."""
        entries = self.declared.setdefault(name, [])
        bound = line, held, top, column
        if (unknown := (line, "?", False, column)) in entries.between(line, line):
            entries[entries.index(unknown)] = bound
        else:
            entries.append(bound)
        return bound

    def _typed_declaration(self, name, column):
        """The declaration of ``name`` with a known type at ``column`` of the
        line being read, or at no column of it, else None."""
        return next(
            (
                d
                for d in self.declared.between(name, self._line, self._line)
                if d[3] in (column, None) and d[1] and d[1][0] not in "#?"
            ),
            None,
        )

    def paren_around(self, column):
        """The column of the innermost `(` of the line being read that is
        open at ``column``, else None."""
        return self._innermost[bisect_right(self._parens, column)]

    def bracket_around(self, column):
        """The innermost bracket open at ``column`` of the line being read:
        its column, None for one an earlier line left open, and its
        character, "" for none."""
        return self._inside[bisect_right(self._brackets, column)]

    def _index_open(self, end):
        """The column of the `[` the `]` before column ``end`` of the line
        being read closes; None where none does."""
        code, depth = self._code, 0
        if code[end - 1 : end] != "]":
            return None
        for at in range(end - 1, -1, -1):
            depth += (code[at] == "]") - (code[at] == "[")
            if not depth:
                return at
        return None

    def _continued_path(self, text):
        """The path ``text``, fields alone with their `.` leading, `.items`,
        goes on to from the name the line before ends with; None for any
        other text."""
        fields = re.fullmatch(r"\s*((?:[?!]{0,2}\.[A-Za-z_$][\w$]*)+)", text)
        named = fields and self._tail is None and self._tail_name
        return named and f"{named}{re.sub(r'[?!]', '', fields[1])}"

    def _element_origin(self, end, callee, lineno, since, source_id):
        """Origin path of a call of ``callee`` on what the code before
        column ``end`` of the line being read, an element access, gives;
        None for no reader of it."""

    def held_around(self, column):
        """What the bracket an earlier line left open that is innermost at
        ``column`` of the line being read holds, by ``_held_label``."""
        return self._inside_labels[bisect_right(self._brackets, column)]

    def _held_label(self, code, column):
        """What the bracket at ``column`` of ``code``, which the line leaves
        open, holds as a call's argument; None for no reader of it."""

    def call_closed_at(self, column):
        """The call whose `)` is at ``column`` of the line being read, as
        ``(edge index, column of its "(")``, else None."""
        edge = self._closes.get(column)
        opened = [start for start, end in self._pairs.items() if end == column]
        return (edge, opened[0]) if edge is not None and opened else None

    def continue_chain(self, column, edge):
        """Read a call that follows the character at ``column`` of the line
        being read as made on what the call at edge index ``edge`` returned."""
        self._closes[column] = edge

    def _binds_file(self, name):
        """Whether what the line being read binds ``name`` to is in scope in
        every definition of the file."""
        return False

    def _sees_file(self):
        """Whether the line being read sees what the file's top level binds."""
        return True

    def free_id(self, node_id):
        """``node_id``, or where a node holds it, the first of `node_id#2`,
        `node_id#3`… that none holds."""
        held, count = node_id, 1
        while held in self.builder.node_registry:
            count += 1
            held = f"{node_id}#{count}"
        return held

    def _nameless_owner(self, parent_id, name, lineno, last, kind="class"):
        """Make the definition ``name`` that source cannot write, held by
        ``parent_id`` and spanning lines ``lineno`` to ``last``: the members
        of a block for no type source can name are its own. Another of the
        name in ``parent_id``, one opened on the same line, is `name#2` and
        so on. Returns its ID."""
        owner_id = self.free_id(f"{parent_id}::{name}")
        self.builder.add_node(
            owner_id,
            "Class",
            name=name,
            kind=kind,
            lineno=lineno,
            end_lineno=last,
            token_count=token_count(lineno, last),
            docstring="",
        )
        self.builder.add_edge(parent_id, owner_id, "DEFINES")
        return owner_id

    def _binds_name(self, name):
        """Whether a line declaring ``name`` gives it a value of this file's
        own."""
        return True

    def declares(self, binding):
        """Whether ``binding``, a match of ``binding_re``, declares its name
        rather than assigning a variable declared before."""
        return True

    def _typed_origin(self, origin, declared):
        """Origin path of a name that a line both declares with the type
        ``declared`` and binds to the call at ``origin``; None where the
        language reads such a name by its type alone."""
        return

    def _is_local(self, name):
        """Whether ``name`` is a parameter or a variable of the definition
        the line being read belongs to."""
        return (self._scope, name) in self._locals

    def add_local(self, scope, name):
        """Record that ``name`` is a parameter or variable of ``scope``: a
        bare call of it there calls a value, not a definition of that name
        from outside ``scope``."""
        self._locals.add((scope, name))

    def _operand(self, text):
        """``(operand, unwraps)`` of the expression ``text``: what it is
        without the operators around it that leave its origin as it is, and
        how many times its value is unwrapped."""
        return text, 0

    def _item_reaches(self, name, declaration, lineno):
        """Whether ``declaration``, a file-level entry of ``declared`` for
        ``name``, is seen where line ``lineno`` is read: it is, but where
        the language scopes such an item to a body."""
        return True

    def _field_types(self, node, owner, field):
        """The types ``field`` is declared with in the type ``node``, named
        ``owner``: on its own lines, where the field was read from lines,
        else those of every type of the name."""
        lines = self._field_lines.get((owner, field))
        if not lines:
            return self.fields[owner, field]
        first = node["metadata"].get("lineno", 0)
        last = node["metadata"].get("end_lineno", first)
        return {held for line, held in lines.items() if first <= line <= last}

    def _constructed(self, text):
        """The type the expression ``text`` constructs where it is one
        construction, as a declaration of it reads, else None."""

    def _closed_value(self, code):
        """Origin path of the value whose last bracket ends ``code``, the
        line being read, where the language reads one, a literal opened on
        a line above; else None."""

    def _item_origin(self, text, lineno, start, since):
        """The origin of a value ``text``, at column ``start`` of line
        ``lineno`` in the definition from line ``since``, that names an item
        rather than a variable, where the language reads one as a value;
        else None."""

    def _expression_origin(self, code, start, end, lineno, since, owner):
        """Origin path of the value of the expression at columns ``start``
        to ``end`` of ``code``, the line being read: of the call chain it
        is, or of the name or the field it reads, or of what both branches
        of a conditional are. None for any other."""
        if branches := _conditional(code, start, end):
            # A conditional's value has the type both its branches give.
            held = {
                self._constructed(code[branch[0] : branch[1]])
                or self._expression_origin(code, *branch, lineno, since, owner)
                for branch in branches
            }
            return held.pop() if len(held) == 1 else None
        plain, unwraps = self._operand(code[start:end].strip())
        unwraps = ".?" * unwraps
        fields = self.call_fields and re.search(r"\)((?:\.[A-Za-z_]\w*)+)$", plain)
        if fields and _is_call_chain(plain[: fields.start(1)]):
            # A field of what a call chain returns
            closed = len(code[:end].rstrip().rstrip("?!")) - len(fields[1]) - 1
            edge = self._closes.get(closed)
            return None if edge is None else f"#{edge}{fields[1]}{unwraps}"
        if plain.endswith(")"):
            edge = self._closes.get(len(code[:end].rstrip().rstrip("?!")) - 1)
            if edge is None or not _is_call_chain(plain):
                return None
            return f"#{edge}{unwraps}"
        names = plain.split(".")
        if names[0][:1].isdigit() or not all(re.fullmatch(r"[\w$]+", n) for n in names):
            # No name: a number, or an expression
            return None
        # `self.field` has the type its struct declares, where this file
        # has that; any further name is a field of what is before it.
        size = 2 if names[0] == self.self_name else 1
        # The name is read where it is written.
        path = ".".join([*names[:size], "x"])
        head = self._read_from(start, self.call_origin, path, lineno, since, owner)
        if (head is None or head[0] == "?") and names[0] != self.self_name:
            return None
        head, size = (head[:-2], size) if head else ("self", 1)
        return ".".join([head, *names[size:]]) + unwraps

    def _rebind(self, name, lineno, column, origin, until=None, after=None):
        """Give ``name``, which a pattern binds at ``column`` of line
        ``lineno`` and which was read as of no declared type, the origin path
        ``origin``, up to ``(line, column)`` ``until`` where the pattern's
        block ends there, from where it is ``after`` again."""
        entries = self.declared.setdefault(name, [])
        # What a block binds, as a `for` does, is the block's.
        top = not until and self._binds_file(name)
        bound = lineno, origin, top, column
        written = [e for e in entries.between(lineno, lineno) if e[3] == column]
        if written:
            entries[entries.index(written[0])] = bound
        else:
            entries.append(bound)
        if until:
            entries.append((until[0], after, False, until[1]))

    def _read_from(self, column, read, *args):
        """What ``read(*args)`` gives with names read at ``column`` of the
        line being read."""
        read_at, self._read_at = self._read_at, column
        found = read(*args)
        self._read_at = read_at
        return found

    def _named_from(self, name, at):
        """The column where the line being read first names ``name`` from
        column ``at``, else ``at``."""
        found = _named(self._code, name, at)
        return at if found is None else found

    def _bind(self, bindings, index, at, block=False, column=0):
        """Give each name of ``bindings`` that a pattern written from column
        ``at`` of line ``index`` binds its origin path there, up to the end
        of the block the line opens from ``column`` on where ``block`` says
        it has one, else to the end of the line, and from there what it held
        before."""
        lineno = index + 1
        until = lineno + 1, 0
        if block:
            text, starts, closer, _ = self._blocks
            if (opened := text.find("{", starts[index] + column)) in closer:
                # From past its `}`
                until = self._place(closer[opened] + 1)
        for name, origin in bindings.items():
            column = self._named_from(name, at)
            # Past the scope, what the name holds where the pattern binds it
            after = self._read_from(column, self._declared, name, lineno, 0)
            self._rebind(name, lineno, column, origin, until, after)

    def _bind_closures(self, code, index, lines, before):
        """Type the parameters of the closures that open before column
        ``before`` of line ``index`` and are arguments of a call, from what
        the call passes to them. ``self._closures`` has, for each closure
        of the line still to be read, the column it starts at, its
        parameters as written and the column its body starts at."""
        while self._closures and self._closures[0][0] < before:
            bar, params, end = self._closures.pop(0)
            opened, bracket = self.bracket_around(bar)
            edge, position, closed = None, "?", None
            if bracket != "(":
                continue
            if opened is not None:
                closed = self._pairs.get(opened)
                edge = self._closes.get(closed, self._opens.get(opened))
                position = (
                    len(
                        _bracketed_parts(
                            code[opened + 1 : bar] + "x",
                            expression=True,
                            turbofish=self.language == "rust",
                        )
                    )
                    - 1
                )
            elif self._open_calls:
                edge = self._open_calls[-1]
            if edge is None:
                continue
            if closed is not None:
                self._bodies.append((edge, position, end, closed))
            # In a block the names last to its end, else to the end of the
            # line or of the call.
            bindings = {
                name: _bound_origin(f"#{edge}|{position}|{number}", steps)
                for number, param in enumerate(_bracketed_parts(params + ")"))
                for name, steps in self.bindings(param)
            }
            body = code[end:]
            if closed is None and not body.strip():
                # A body on the lines after is in scope to the statement's end.
                until = _statement_end(lines, index) + 2, 0
                for name, origin in bindings.items():
                    column = self._named_from(name, bar)
                    self._rebind(name, index + 1, column, origin, until)
                continue
            block = closed is None and body.count("{") > body.count("}")
            self._bind(bindings, index, bar, block, end)

    def _name_results(self, code, lineno, since, owner):
        """Add to the origin path of each call that was passed a closure on
        the line what the closure returns, `{argument=origin}`, where its
        body is one call or one name whose origin is a call or a closure's
        parameter."""
        for edge, position, start, end in self._bodies:
            metadata = self.builder.edges[edge]["metadata"]
            body = self._expression_origin(code, start, end, lineno, since, owner)
            if body and re.fullmatch(r"#[\d|?]+", body) and "origin" in metadata:
                passed = f"{position}={body}"
                joined = metadata["origin"].endswith("}")
                metadata["origin"] = (
                    f"{metadata['origin'][:-1]},{passed}}}"
                    if joined
                    else f"{metadata['origin']}{{{passed}}}"
                )

    def _local_at(self, source_id, name, lineno, column):
        """Whether ``name``, read at ``column`` of line ``lineno``, is a
        local of ``source_id``."""
        return (source_id, name) in self._locals

    def add_call(self, source_id, callee, lineno, since, start, paren, origin=None):
        """Record a call of ``callee`` from ``source_id`` on ``lineno``, the
        line given to ``begin_line``. ``start`` and ``paren`` are the columns
        in it of the callee and of the `(` after it. A call on the result of
        another call (`a().b()`, or `.b()` on the next line) gets an origin
        path that names that call by its edge index, unless ``origin`` gives
        one, and the edge carries the column of the called name for a SCIP
        lookup."""
        name_start = start + len(callee) - len(_split_callee(callee)[1])
        written = None
        if origin is None:
            # The code before the callee ends at ``end``, and the code before
            # a `.` there at ``receiver``, or without its `?` at ``called``.
            end = _run_start(self._code, start)
            dot = self._code[end - 1 : end] == "." if end else self._tail_dot
            receiver = _run_start(self._code, end - 1) if end else 0
            # A line that opens with `?.` or `!.` goes on from the one before.
            lead = self._code[: end - 1].strip() if dot else ""
            marks = len(lead) if lead and not lead.strip("?!") else 0
            receiver = 0 if marks else receiver
            if dot and not receiver and self._tail is None and self._tail_element:
                # The receiver is the element the line before ends with.
                origin = f"{self._tail_element}.{callee}"
            elif dot and not receiver and self._tail is None and self._tail_name:
                # The receiver is the name the line before ends with.
                callee = f"{self._tail_name}.{callee}"
            elif (
                dot
                and self.language == "rust"
                and (held := self._parenthesized(receiver))
            ):
                # `(*v).m()`: the method of what `v` is, through the borrow
                # the parentheses write
                callee, written = f"{held[0]}.{callee}", held[1]
            elif dot and self._code[max(end - 2, 0) : end] != "..":
                # `?` unwraps a value; TypeScript's `!` asserts it is not null.
                called = receiver
                while called and self._code[called - 1] in "?!":
                    called -= 1
                edge = self._closes.get(called - 1) if receiver else self._tail
                unwrap = ".?" * (
                    receiver - called if receiver else self._tail_unwraps + marks
                )
                unwrap = unwrap if receiver else self._tail_fields + unwrap
                # A member is looked up by its name, `get<T>` as `get`.
                member = _strip_generics(callee)
                origin = (
                    f"#{edge}{unwrap}.{member}"
                    if edge is not None
                    else self._element_origin(called, member, lineno, since, source_id)
                    or f"?.{member}"
                )
        if origin is None and self._local_at(source_id, callee, lineno, start):
            origin = f"={callee}"
        owner = self._owning_type(source_id)
        self._read_at = start
        origin = origin or self.call_origin(callee, lineno, since, owner)
        self._read_at = None
        metadata = {"lineno": lineno}
        if origin:
            metadata["origin"] = origin
        at, units = self._units if name_start >= self._units[0] else (0, (0, 0, 0))
        self._units = name_start, _code_units(self._raw[at:name_start], units)
        metadata["col"] = _scip_columns(self._units[1])
        index = len(self.builder.edges)
        self.builder.add_edge(source_id, f"REF:{callee}", "CALLS", metadata)
        if written is not None:
            metadata["site"] = {"receiver": written}
        if paren in self._pairs:
            self._closes[self._pairs[paren]] = index
        elif paren in self._opens:
            self._opens[paren] = index

    def _parenthesized(self, end):
        """``(name, whether it is a reference)`` of the receiver the code
        before column ``end`` of the line closes, `(*v)`, `(&v)`, `(&mut v)`
        or `(v)`; None for any other."""
        opened = [start for start, close in self._pairs.items() if close == end - 1]
        # Parentheses of their own, not a call's or a macro's
        before = opened and self._code[: opened[0]].rstrip()[-1:]
        inner = (
            opened
            and not re.match(r"[\w)\]>!?]", before or " ")
            and (self._code[opened[0] + 1 : end - 1])
        )
        found = inner and re.fullmatch(
            r"\s*([*&]?)\s*(?:mut\s+)?([A-Za-z_]\w*)\s*", inner
        )
        if not found:
            return None
        return found[2], {"*": False, "&": True}.get(found[1])

