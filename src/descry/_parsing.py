# Spaces, read from an offset: `_SPACES.match(text, at).end()` is past them.
_SPACES = re.compile(r"\s*")


def _flat(text):
    """``text`` without its brackets and what they hold, nested ones too."""
    flat, wider = text, None
    while flat != wider:
        wider, flat = flat, re.sub(r"\([^()]*\)|\[[^\[\]]*\]|\{[^{}]*\}", "", flat)
    return flat


def _blank(match):
    """Spaces as long as what ``match`` matched: columns stay where they were."""
    return " " * len(match[0])


def source_lines(content):
    """The lines of ``content``, read as text, numbered as an editor and
    ``readlines`` number them: split at `\\n` alone, where
    ``str.splitlines`` also splits at `\\v`, `\\f` and other characters
    that end no line of source."""
    lines = content.split("\n")
    return lines[:-1] if lines[-1] == "" else lines


def is_generated_source(content: str) -> bool:
    """True if the file looks like autogenerated code.

    Checked against the first 30 lines — generators
    almost always stamp a marker comment in the header (Go's
    well-known "// Code generated ... DO NOT EDIT", protoc-gen-go,
    C autoconf output, @generated from Buck/Facebook, etc.). False
    positives here only cost us the CALLS edges from that file; node
    extraction still runs so cross-file references can still resolve.
    """
    head = "\n".join(source_lines(content)[:30])
    return any(marker in head for marker in _GENERATED_MARKERS)


# A definition's size estimate: tokens to a line of its source
_TOKENS_PER_LINE = 10


def token_count(first, last):
    """The size estimate of a definition on lines ``first`` to ``last``."""
    return (last - first + 1) * _TOKENS_PER_LINE


def merge_import(imports, key, value):
    """Bind ``key`` in ``imports`` to the import target ``value``: to it
    alone, or, where another target is bound already, to each as a tuple,
    since which one the name names is not told."""
    held = imports.get(key)
    if held is None or held == value:
        imports[key] = value
    elif isinstance(held, tuple):
        if value not in held:
            imports[key] = (*held, value)
    else:
        imports[key] = (held, value)


class SymbolTable:
    def __init__(self):
        # Maps local_alias -> fully_qualified_name
        self.imports = {}

    def add_import(self, name, module=None, alias=None):
        key = alias if alias else name
        if module:
            value = f"{module}.{name}"
        else:
            value = name
        merge_import(self.imports, key, value)

    def resolve(self, name):
        parts = name.split(".")
        root = parts[0]
        if root in self.imports:
            resolved_root = self.imports[root]
            if isinstance(resolved_root, tuple):
                # Several imports of the name fit; which one it names is
                # not told.
                return name
            if len(parts) > 1:
                return f"{resolved_root}.{'.'.join(parts[1:])}"
            return resolved_root
        return name


