"""Write the tool reference, `docs/TOOLS.md`: each tool's parameters as the
MCP server declares them, its answer as `CONTRACT.md` writes it, how each
interface names it, and what `descry <tool> ... --json` answers on the Python
ground-truth project.

usage: gen_tools.py OUTPUT
"""

import asyncio
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from descry.cli import build_parser
from descry.mcp_server import mcp
from descry.web.server import routes

REPO = Path(__file__).resolve().parents[2]
PROJECT = REPO / "tests" / "ground_truth" / "python"
POSTED = {
    r.path.removeprefix("/api/") for r in routes if "POST" in getattr(r, "methods", ())
}
# Web routes that take none of the tool's parameters
UNPARAMETERED = {"index"}

# Tool -> its CLI arguments, for the tools whose answer the project decides;
# the others' depend on the clock, git or a model.
EXAMPLES = {
    "callers": "load",
    "callees": "main",
    "context": "rename --brief",
    "flow": "main --depth 2",
    "path": "main save",
    "quick": "load",
    "search": "parse",
    "structure": "app/models.py",
    "flatten": "User",
}
AMBIGUOUS = "callers parse"


def contract():
    """Tool -> (parameters, answer) as the Tools table of CONTRACT.md has them."""
    rows = {}
    for line in (REPO / "CONTRACT.md").read_text().splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 3 and cells[0].startswith("`"):
            for tool in re.findall(r"`(\w+)`", cells[0]):
                rows[tool] = cells[1], cells[2]
    return rows


def usages():
    """CLI command -> its usage line."""
    parser = build_parser()
    commands = next(a for a in parser._actions if a.dest == "command").choices
    return {
        name: " ".join(sub.format_usage().split()).replace(" [-h]", "")
        for name, sub in commands.items()
    }


def answers():
    """Tool -> what the CLI answers on the ground-truth project, and what it
    answers for a name two definitions share."""
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp) / "project"
        shutil.copytree(PROJECT, root, ignore=shutil.ignore_patterns("expected.json"))
        env = {
            **os.environ,
            "DESCRY_NO_SCIP": "1",
            "DESCRY_NO_EMBEDDINGS": "1",
            "XDG_STATE_HOME": str(Path(tmp) / "state"),
        }

        def cli(arguments):
            command = [sys.executable, "-m", "descry.cli", *arguments.split()]
            run = subprocess.run(
                command, cwd=root, env=env, capture_output=True, text=True, check=False
            )
            return run.stdout

        cli("index")
        held = {
            tool: json.loads(cli(f"{tool.replace('_', '-')} {arguments} --json"))
            for tool, arguments in EXAMPLES.items()
        }
        return held, json.loads(cli(f"{AMBIGUOUS} --json"))


def parameter_rows(schema):
    required = set(schema.get("required", ()))
    for name, spec in schema.get("properties", {}).items():
        options = [
            schema["$defs"][o["$ref"].rpartition("/")[2]] if "$ref" in o else o
            for o in spec.get("anyOf", [spec])
        ]
        kinds = [
            " or ".join(f"`{v}`" for v in o["enum"]) if "enum" in o else o.get("type")
            for o in options
        ]
        kind = " or ".join(k for k in kinds if k and k != "null") or "any"
        default = "required" if name in required else json.dumps(spec.get("default"))
        yield f"| `{name}` | {kind} | {default} |"


def write(output):
    rows, cli = contract(), usages()
    examples, failure = answers()
    tools = asyncio.run(mcp.list_tools())
    out = [
        "# Tool reference",
        "",
        "Generated by `tools/docs/gen_tools.py` from the MCP server's tools,",
        "`CONTRACT.md` and the CLI; do not edit. The examples are answers",
        "from `tests/ground_truth/python`. Rules, failures and the entries an",
        "answer lists are in `CONTRACT.md`.",
        "",
        "A name two definitions share is refused with the choices:",
        "",
        "```json",
        json.dumps(failure, indent=2),
        "```",
    ]
    for tool in tools:
        name = tool.name.removeprefix("descry_")
        command = name.replace("_", "-")
        verb = "POST" if name in POSTED else "GET"
        out += [
            "",
            f"## {name}",
            "",
            tool.description.strip(),
            "",
            *(
                ["| parameter | type | default |", "|---|---|---|", *params]
                if (params := list(parameter_rows(tool.input_schema)))
                else ["No parameters."]
            ),
            "",
            f"Answer: {rows[name][1]}" if name in rows else "",
            "",
            f"MCP `{tool.name}`; web `{verb} /api/{command}`"
            + (" (no parameters)" if name in UNPARAMETERED else "")
            + f"; CLI `{cli[command]}`",
        ]
        if name in examples:
            out += [
                "",
                f"`descry {command} {EXAMPLES[name]} --json`:",
                "",
                "```json",
                json.dumps(examples[name], indent=2),
                "```",
            ]
    Path(output).write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    if len(sys.argv) != 2 or sys.argv[1].startswith("-"):
        sys.exit("usage: gen_tools.py OUTPUT")
    write(sys.argv[1])
